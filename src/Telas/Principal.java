    private String verificaModo() {
        String modoJogo;
        if (JCBPVP.isSelected()) {
            modoJogo = "pvp";
            return modoJogo;
        }

        if (JCBIAfacil.isSelected()) {
            modoJogo = "ia_facil";
            return modoJogo;
        }

        if (JCBIADificil.isSelected()) {
            modoJogo = "ia_dificil";
            return modoJogo;
        }
        return "";
    }

    private void resetaJogo() {
        contadorJogada = 0;
        limpaBotoes();
        habilitaBotoes(false);
        preencheMatriz();
        jBnovo.setEnabled(true);
        habilitaCheckBox(true);
    }

